export const similarProperties = (p: Property, n = 3) =>
  properties.filter((x) => x.id !== p.id && x.category === p.category).slice(0, n);
export const propertiesInEstate = (estateSlug: string) => properties.filter((p) => p.estateSlug === estateSlug);
