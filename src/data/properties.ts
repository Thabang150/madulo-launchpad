export interface PropertyFilters {
  q?: string;
  category?: PropertyCategory | "";
  type?: string;
  listing?: ListingType | "";
  maxPrice?: number;
  beds?: number;
}

export function filterProperties(list: Property[], f: PropertyFilters) {
  return list.filter((p) => {
    if (f.category && f.category !== p.category && !p.tags?.includes(f.category)) return false;
    if (f.type && p.type !== f.type) return false;
    if (f.listing && p.listing !== f.listing) return false;
    if (f.maxPrice && p.price > f.maxPrice) return false;
    if (f.beds && (p.bedrooms ?? 0) < f.beds) return false;
    if (f.q) {
      const hay = `${p.title} ${p.type} ${p.location.suburb} ${p.location.city} ${p.location.province}`.toLowerCase();
      if (!hay.includes(f.q.toLowerCase())) return false;
    }
    return true;
  });
}

export const getProperty = (slug: string) => properties.find((p) => p.slug === slug);
